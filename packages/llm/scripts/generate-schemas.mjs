#!/usr/bin/env node
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(here, '..');
const schemasRoot = join(packageRoot, 'schemas');
const outFile = join(packageRoot, 'src', 'schemas.generated.ts');

const files = readdirSync(schemasRoot)
  .filter((entry) => entry.endsWith('.json'))
  .sort();

const entries = files.map((file) => {
  const text = readFileSync(join(schemasRoot, file), 'utf8');
  const schema = JSON.parse(text);
  if (typeof schema.$id !== 'string') throw new Error(`${file} is missing $id`);
  return { file, id: schema.$id, text };
});

const body = entries
  .map((entry) => `  ${JSON.stringify(entry.id)}: ${entry.text.trim()},`)
  .join('\n');

const output = `// Generated by scripts/generate-schemas.mjs. Do not edit by hand.\n// Source of truth: packages/llm/schemas/*.json\nexport const SCHEMA_SOURCES: Readonly<Record<string, unknown>> = {\n${body}\n};\n`;

writeFileSync(outFile, output, 'utf8');
console.log(`wrote ${entries.length} schema(s) to ${relative(packageRoot, outFile)}`);
