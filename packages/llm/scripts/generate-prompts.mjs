#!/usr/bin/env node
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(here, '..');
const promptsRoot = join(packageRoot, 'prompts');
const outFile = join(packageRoot, 'src', 'prompts.generated.ts');

const toPosix = (value) => value.split(sep).join('/');

const files = [];
const walk = (dir) => {
  for (const entry of readdirSync(dir).sort()) {
    const absolute = join(dir, entry);
    if (statSync(absolute).isDirectory()) walk(absolute);
    else if (entry.endsWith('.md')) files.push(absolute);
  }
};
walk(promptsRoot);

const entries = files.map((file) => {
  const rel = toPosix(relative(promptsRoot, file));
  const match = /^(.*)\/([^/]+)\.md$/.exec(rel);
  if (match === null) throw new Error(`unexpected prompt path: ${rel}`);
  const [, id, version] = match;
  return { key: `${id}@${version}`, text: readFileSync(file, 'utf8'), id, version };
});

entries.sort((a, b) => a.key.localeCompare(b.key));

const body = entries
  .map((entry) => `  ${JSON.stringify(entry.key)}: ${JSON.stringify(entry.text)},`)
  .join('\n');

const output = `// Generated by scripts/generate-prompts.mjs. Do not edit by hand.\n// Source of truth: packages/llm/prompts/<id>/<version>.md\nexport const PROMPTS: Readonly<Record<string, string>> = {\n${body}\n};\n`;

writeFileSync(outFile, output, 'utf8');
console.log(`wrote ${entries.length} prompt(s) to ${toPosix(relative(packageRoot, outFile))}`);
