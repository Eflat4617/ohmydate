#!/usr/bin/env node
// Generate the local-only secret files. Values are never printed.
import { randomBytes } from 'node:crypto';
import { chmod, stat } from 'node:fs/promises';
import {
  createContext,
  ensureDir,
  fail,
  isEntryPoint,
  log,
  parseFlags,
  readEnvFile,
  writeFileExclusive,
} from './common.mjs';

const STACK_KEYS = ['postgres.env', 'vikunja.env', 'push.key', 'llm-session-secret', 'google-token.key'];

async function existingMode(path) {
  try {
    const info = await stat(path);
    return info.mode & 0o777;
  } catch {
    return null;
  }
}

async function writeIfMissing(path, content, created, existing) {
  try {
    await writeFileExclusive(path, content, 0o600);
    await chmod(path, 0o600);
    created.push(path);
    return true;
  } catch (error) {
    if (error !== null && typeof error === 'object' && error.code === 'EEXIST') {
      if ((await existingMode(path)) !== 0o600) {
        await chmod(path, 0o600).catch(() => undefined);
      }
      existing.push(path);
      return false;
    }
    throw error;
  }
}

export async function initSecrets(options = {}) {
  const context = options.context ?? createContext(options.env ?? process.env);
  await ensureDir(context.secretsDir, 0o700);
  await chmod(context.secretsDir, 0o700);

  const created = [];
  const existing = [];

  // Legacy single-file secrets: split them without changing the values so an
  // existing database stays reachable after the postgres/vikunja split.
  const legacy = readEnvFile(context.legacyStackEnvPath);
  const existingPostgres = readEnvFile(context.postgresEnvPath);
  const postgresPassword =
    existingPostgres.POSTGRES_PASSWORD ??
    legacy.POSTGRES_PASSWORD ??
    randomBytes(24).toString('base64url');
  const serviceSecret = legacy.VIKUNJA_SERVICE_SECRET ?? randomBytes(32).toString('hex');
  const vikunjaDatabasePassword = legacy.VIKUNJA_DATABASE_PASSWORD ?? postgresPassword;

  await writeIfMissing(
    context.postgresEnvPath,
    [
      '# Generated by scripts/local/secrets.mjs. Never commit this file.',
      `POSTGRES_PASSWORD=${postgresPassword}`,
      '',
    ].join('\n'),
    created,
    existing,
  );
  await writeIfMissing(
    context.vikunjaEnvPath,
    [
      '# Generated by scripts/local/secrets.mjs. Never commit this file.',
      `VIKUNJA_DATABASE_PASSWORD=${vikunjaDatabasePassword}`,
      `VIKUNJA_SERVICE_SECRET=${serviceSecret}`,
      '',
    ].join('\n'),
    created,
    existing,
  );
  await writeIfMissing(
    context.pushKeyFile,
    `${randomBytes(32).toString('hex')}\n`,
    created,
    existing,
  );
  await writeIfMissing(
    context.sessionSecretFile,
    `${randomBytes(32).toString('hex')}\n`,
    created,
    existing,
  );
  // CAL-03: AES-256-GCM key for the Google refresh token (GOOGLE_TOKEN_KEY_FILE).
  await writeIfMissing(
    context.googleTokenKeyFile,
    `${randomBytes(32).toString('hex')}\n`,
    created,
    existing,
  );

  return {
    secretsDir: context.secretsDir,
    created: created.map((path) => path.slice(context.secretsDir.length + 1)),
    existing: existing.map((path) => path.slice(context.secretsDir.length + 1)),
  };
}

async function main() {
  const { flags } = parseFlags(process.argv.slice(2));
  if (flags.has('help')) {
    console.log('usage: node scripts/local/secrets.mjs init');
    return;
  }
  const result = await initSecrets();
  log(`비밀 디렉터리: ${result.secretsDir}`);
  log(`새로 만든 파일: ${result.created.length > 0 ? result.created.join(', ') : '없음'}`);
  log(`기존 파일 유지: ${result.existing.length > 0 ? result.existing.join(', ') : '없음'}`);
  log('값은 출력하지 않습니다.');
}

if (isEntryPoint(import.meta.url)) {
  await main().catch((error) => {
    fail(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  });
}

export { STACK_KEYS };
